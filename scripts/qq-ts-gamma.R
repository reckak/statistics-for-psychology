# Pointwise levels γ(n) of the tail-sensitive simultaneous 95 % band for the normal Q–Q plot
# (Aldor-Noiman et al., 2013) with the algorithm of qqplotr::stat_qq_band(bandType = "ts"): the band at rank i runs
# between the quantiles γ and 1 − γ of Beta(i, n + 1 − i), transformed by qnorm(·) · s + m. As in qqplotr's default
# (parameters estimated from the data) the simulated samples are standardized before the transformation, so that
# the band keeps its 95 % simultaneous coverage although m and s are estimated; qqplotr standardizes by robust
# estimates (Qn), the app by the mean and SD of chapter 4. (With mu and sigma given, qqplotr simulates uniform
# samples instead; with m and s estimated from the same data such a band covers almost 100 %.)
# qqplotr draws B = 1000 samples on every call; here B is much larger and the seed fixed, so the table
# (used by assets/stat/normalita.js for the app page quarto/app_jeden_prumer.qmd) is reproducible and has
# a smaller Monte Carlo error. Run from the project root (takes a few minutes):
#   Rscript --vanilla scripts/qq-ts-gamma.R
# Writes assets/stat/qq-ts-gamma.js.
options(digits = 15)
set.seed(20261127)
conf <- 0.95
ns <- c(3:30, seq(35, 100, 5), seq(120, 300, 20), 350, 400, 500, 600, 700, 800, 1000, 1250, 1500, 2000,
        2500, 3000, 4000, 5000)
gammaFor <- function(n, B) {
  crit <- numeric(0)
  chunk <- max(1, floor(2e6 / n))
  done <- 0
  while (done < B) {
    b <- min(chunk, B - done)
    # Normal samples standardized by their own mean and SD (the parameters are estimated from the data, as the
    # app's band m + s·z), then transformed to the uniform scale: as qqplotr's default "ts" band, which
    # standardizes by robust estimates (Qn) instead.
    z <- apply(matrix(rnorm(n * b), n, b), 2, function(v) sort((v - mean(v)) / sd(v)))
    u <- pnorm(z)
    p <- pbeta(u, shape1 = 1:n, shape2 = n:1)            # recycled down each column: rank i
    crit <- c(crit, apply(pmin(p, 1 - p), 2, min))
    done <- done + b
  }
  unname(quantile(crit, probs = 1 - conf))               # type 7, as in qqplotr
}
B <- 50000
res <- vapply(ns, function(n) gammaFor(n, if (n <= 1000) B else 20000), numeric(1))
# The Monte Carlo values are smoothed on the log–log scale (γ(n) decreases smoothly with n); the smoothed values
# are used, the raw ones are kept for comparison.
fit <- smooth.spline(log(ns), log(res), df = 10)
sm <- exp(predict(fit, log(ns))$y)
# Up to n = 30 the raw values (B = 50 000, every n in the table) are kept: the spline is least accurate at the end
# of the range (n = 3 smoothed by −2,5 % gave coverage 0,966).
sm[ns <= 30] <- res[ns <= 30]
cat(sprintf("n = %d: gamma = %.6g, smoothed %.6g (%+.1f %%)\n", ns, res, sm, 100 * (sm / res - 1)), sep = "")
lines <- c(
  "// Generated by scripts/qq-ts-gamma.R; do not edit by hand.",
  "// Pointwise level γ(n) of the tail-sensitive simultaneous 95 % band of the normal Q–Q plot",
  sprintf("// (Aldor-Noiman et al., 2013; qqplotr bandType = \"ts\"), Monte Carlo with B = %d (n > 1000: 20000), seed 20261127,", B),
  "// smoothed on the log–log scale above n = 30 (smooth.spline, df = 10); TS_GAMMA_RAW holds the unsmoothed Monte Carlo values.",
  sprintf("export const TS_CONF = %s;", conf),
  sprintf("export const TS_N = [%s];", paste(ns, collapse = ", ")),
  sprintf("export const TS_GAMMA = [%s];", paste(signif(sm, 8), collapse = ", ")),
  sprintf("export const TS_GAMMA_RAW = [%s];", paste(signif(res, 8), collapse = ", "))
)
writeLines(lines, "assets/stat/qq-ts-gamma.js", useBytes = TRUE)
